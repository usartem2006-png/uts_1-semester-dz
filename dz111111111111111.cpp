#include <iostream>   // для ввода/вывода
#include <vector>
using namespace std;

// Функция для вывода матрицы на экран
void printMatrix(const vector<vector<int>>& matrix) {
    for (const auto& row : matrix) {      // Для каждой строки матрицы
        for (int val : row) {            // Для каждого числа в строке
            cout << val << " ";          // Выводим число
        }
        cout << endl;                    // Переход на новую строку
    }
}

// Основная функция для решения задачи 5
void swapMinWithDiagonal(vector<vector<int>>& matrix) {
    // Узнаем размер матрицы (квадратная, поэтому строк = столбцов)
    int n = matrix.size();
    
    // Перебираем все строки матрицы
    for (int row = 0; row < n; row++) {
        
        // ШАГ 1: Ищем минимальный элемент в текущей строке
        // Начинаем с предположения, что первый элемент - минимальный
        int minValue = matrix[row][0];   // Значение минимального элемента
        int minCol = 0;                  // Столбец, где находится минимум
        
        // Проверяем все элементы строки, начиная со второго
        for (int col = 1; col < n; col++) {
            // Если нашли элемент меньше текущего минимума
            if (matrix[row][col] < minValue) {
                // Запоминаем новый минимум
                minValue = matrix[row][col];
                minCol = col;  // Запоминаем, в каком столбце он находится
            }
        }
        
        // ШАГ 2: Меняем местами минимальный элемент и элемент на диагонали
        // Диагональный элемент находится на пересечении текущей строки и столбца с таким же номером
        // Например, для строки 2 диагональный элемент - matrix[2][2]
        
        // Меняем только если минимум НЕ находится на диагонали
        if (minCol != row) {
            // Сохраняем диагональный элемент во временную переменную
            int temp = matrix[row][row];
            
            // На место диагонального элемента ставим минимальный
            matrix[row][row] = matrix[row][minCol];
            
            // На место минимального элемента ставим бывший диагональный
            matrix[row][minCol] = temp;
            
            // Можно было бы использовать: swap(matrix[row][row], matrix[row][minCol]);
        }
    }
}

int main() {
    // Создаем тестовую матрицу 3x3
    vector<vector<int>> matrix = {
        {4, 1, 3},   // Строка 0
        {2, 5, 6},   // Строка 1
        {9, 7, 8}    // Строка 2
    };
    
    // Диагональные элементы: 4 (0,0), 5 (1,1), 8 (2,2)
    
    cout << "Исходная матрица:" << endl;
    printMatrix(matrix);
    
    // Вызываем нашу функцию
    swapMinWithDiagonal(matrix);
    
    cout << "После перестановки минимального элемента строки с диагональным:" << endl;
    printMatrix(matrix);
    
    return 0;
}